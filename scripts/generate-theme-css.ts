/**
 * Generates CSS custom properties for all 16 TUI themes.
 * Output: packages/web-ui/src/themes/generated.css
 *
 * Usage: bun scripts/generate-theme-css.ts
 */

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  darkTheme,
  lightTheme,
  nordTheme,
  draculaTheme,
  catppuccinMochaTheme,
  catppuccinLatteTheme,
  solarizedDarkTheme,
  solarizedLightTheme,
  gruvboxDarkTheme,
  gruvboxLightTheme,
  tokyoNightTheme,
  oneDarkTheme,
  monokaiTheme,
  githubDarkTheme,
  githubLightTheme,
  rosePineTheme,
} from "../src/tui/shared/themes/index.js";
import type { Theme } from "../src/tui/shared/themes/types.js";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const OUTPUT_PATH = resolve(__dirname, "../packages/web-ui/src/themes/generated.css");

const ALL_THEMES: Theme[] = [
  darkTheme,
  lightTheme,
  nordTheme,
  draculaTheme,
  catppuccinMochaTheme,
  catppuccinLatteTheme,
  solarizedDarkTheme,
  solarizedLightTheme,
  gruvboxDarkTheme,
  gruvboxLightTheme,
  tokyoNightTheme,
  oneDarkTheme,
  monokaiTheme,
  githubDarkTheme,
  githubLightTheme,
  rosePineTheme,
];

function themeToCSS(theme: Theme): string {
  const vars: string[] = [];

  // gradient
  vars.push(`  --gradient-start: ${theme.gradient.start};`);
  vars.push(`  --gradient-middle: ${theme.gradient.middle};`);
  vars.push(`  --gradient-end: ${theme.gradient.end};`);

  // colors
  for (const [key, value] of Object.entries(theme.colors)) {
    const cssKey = key.replace(/([A-Z])/g, "-$1").toLowerCase();
    vars.push(`  --color-${cssKey}: ${value};`);
  }

  // borders
  for (const [key, value] of Object.entries(theme.borders)) {
    vars.push(`  --border-${key}: ${value};`);
  }

  // components — flatten to CSS vars
  for (const [component, props] of Object.entries(theme.components)) {
    const compKey = component.replace(/([A-Z])/g, "-$1").toLowerCase();
    for (const [prop, value] of Object.entries(props as Record<string, string>)) {
      const propKey = prop.replace(/([A-Z])/g, "-$1").toLowerCase();
      vars.push(`  --${compKey}-${propKey}: ${value};`);
    }
  }

  return vars.join("\n");
}

export function generateThemeCSS(): string {
  const blocks: string[] = [];

  blocks.push("/* Auto-generated by scripts/generate-theme-css.ts — DO NOT EDIT */");
  blocks.push("");

  for (const theme of ALL_THEMES) {
    const selector = `[data-theme="${theme.name}"]`;
    const vars = themeToCSS(theme);
    blocks.push(`${selector} {`);
    blocks.push(vars);
    blocks.push("}");
    blocks.push("");
  }

  // System preference defaults
  const darkVars = themeToCSS(darkTheme);
  blocks.push("@media (prefers-color-scheme: dark) {");
  blocks.push("  :root {");
  blocks.push(darkVars.replace(/^/gm, "  "));
  blocks.push("  }");
  blocks.push("}");
  blocks.push("");

  const lightVars = themeToCSS(lightTheme);
  blocks.push("@media (prefers-color-scheme: light) {");
  blocks.push("  :root {");
  blocks.push(lightVars.replace(/^/gm, "  "));
  blocks.push("  }");
  blocks.push("}");
  blocks.push("");

  return blocks.join("\n");
}

// Only write to disk when run directly (not imported by tests)
if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith("generate-theme-css.ts")) {
  const css = generateThemeCSS();
  mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
  writeFileSync(OUTPUT_PATH, css, "utf8");
  console.log(`✅ Generated ${ALL_THEMES.length} themes → ${OUTPUT_PATH}`);
}